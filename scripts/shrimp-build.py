"""Build the animated shrimp's body markup.

Inputs (made by scripts/shrimp-legs.py in the same working directory):
  body.bmp         full traced shrimp minus whiskers (for measuring)
  body-nolegs.bmp  shrimp minus whiskers, legs and tail fan
  leg-*.bmp, tail.bmp, legs.json

The abdomen curls around C; its segment joints run roughly along rays from C, so the body
is cut into the head (carapace) plus seven abdomen pieces by angle. Pieces are nested so each
one carries everything behind it; each rotates a little about a pivot on its front joint.
CSS rotates with `transform-box: fill-box; transform-origin: 50% 50%`, so every moving group
gets an invisible box centred on its pivot, large enough to contain the whole group while it moves.

Writes src/components/shrimp-body.ts (run from the repo root, with the inputs in --work).
"""
import json, math, re, subprocess, sys, os
from PIL import Image

work = sys.argv[sys.argv.index("--work") + 1] if "--work" in sys.argv else "."
C = (990, 840)
JOINTS = [88, 117, 141, 166, 186, 212, 240]   # degrees, counter-clockwise from +x, image y up
LEG_HOST = {"leg-a": 0, "leg-b": 0, "leg-c": 0, "leg-d": 2, "leg-e": 3, "tail": 7}  # 0 = head
G = 'transform="translate(0,1614) scale(0.1,-0.1)"'

def angle(x, y):
    return math.degrees(math.atan2(C[1] - y, x - C[0])) % 360

OVERLAP = 3.0   # degrees each piece reaches into its neighbours, so no seam opens while they bend
RANGES = [(-60, JOINTS[0])] + [(JOINTS[i], JOINTS[i + 1]) for i in range(len(JOINTS) - 1)] + [(JOINTS[-1], 300)]

def pieces_of(x, y):
    a = angle(x, y)
    if a >= 300: a -= 360
    return [k for k, (lo, hi) in enumerate(RANGES) if lo - OVERLAP <= a < hi + OVERLAP]

body = Image.open(os.path.join(work, "body-nolegs.bmp")).convert("L")
W, H = body.size
pb = body.load()
pieces = [Image.new("L", (W, H), 255) for _ in range(len(JOINTS) + 1)]
pp = [p.load() for p in pieces]
boxes = [[W, H, 0, 0] for _ in pieces]
for y in range(H):
    for x in range(W):
        if pb[x, y] == 0:
            for k in pieces_of(x, y):
                pp[k][x, y] = 0
                b = boxes[k]; b[0] = min(b[0], x); b[1] = min(b[1], y); b[2] = max(b[2], x); b[3] = max(b[3], y)

def trace(img, name):
    bmp = os.path.join(work, name + ".bmp"); svg = os.path.join(work, name + ".svg")
    img.convert("1").save(bmp)
    subprocess.run(["potrace", bmp, "-s", "-o", svg, "--turdsize", "8", "--alphamax", "1.0", "--opttolerance", "0.4"], check=True)
    return paths(name)

def paths(name):
    svg = open(os.path.join(work, name + ".svg")).read()
    return " ".join(re.sub(r"\s+", " ", p) for p in re.findall(r'<path d="[^"]*"/>', svg, re.S))

piece_paths = [trace(p, f"piece-{i}") for i, p in enumerate(pieces)]

# pivot for joint k: middle of the body along the ray at that angle
solid = Image.open(os.path.join(work, "body.bmp")).convert("L").load()
pivots = []
for th in JOINTS:
    a = math.radians(th); rs = []
    for r in range(80, 1500, 2):
        x, y = int(C[0] + r * math.cos(a)), int(C[1] - r * math.sin(a))
        if 0 <= x < W and 0 <= y < H and solid[x, y] == 0: rs.append(r)
    r = (min(rs) + max(rs)) / 2
    pivots.append((round(C[0] + r * math.cos(a)), round(C[1] - r * math.sin(a))))

legs = json.load(open(os.path.join(work, "legs.json")))
def leg_box(n):
    x, y, w, h = legs[n]["pad"]; return [x, y, x + w, y + h]
def leg_markup(n):
    x, y, w, h = legs[n]["pad"]
    cls = "tail" if n == "tail" else f"leg {n}"
    if n == "tail": cls = "leg tail"
    return f'<g class="{cls}"><rect x="{x}" y="{y}" width="{w}" height="{h}" fill="none"/><g {G}>{paths(n)}</g></g>'

def union(bs):
    return [min(b[0] for b in bs), min(b[1] for b in bs), max(b[2] for b in bs), max(b[3] for b in bs)]

def subtree_box(k):  # pieces k..7 and their legs
    bs = [boxes[i] for i in range(k, len(pieces))] + [leg_box(n) for n, h in LEG_HOST.items() if h >= k]
    return union(bs)

markup = ""
for k in range(len(pieces) - 1, 0, -1):     # build innermost (last segment) first
    px, py = pivots[k - 1]
    b = subtree_box(k)
    reach = max(math.hypot(cx - px, cy - py) for cx in (b[0], b[2]) for cy in (b[1], b[3]))
    half = round(reach * 1.08 + 20)          # room for the whole group to swing without growing the box
    own_legs = "".join(leg_markup(n) for n, h in LEG_HOST.items() if h == k)
    markup = (f'<g class="seg seg-{k}"><rect x="{px - half}" y="{py - half}" width="{2 * half}" height="{2 * half}" fill="none"/>'
              f'<g {G}>{piece_paths[k]}</g>{own_legs}{markup}</g>')
head_legs = "".join(leg_markup(n) for n, h in LEG_HOST.items() if h == 0)
markup = f'<g {G}>{piece_paths[0]}</g>{head_legs}{markup}'

with open("src/components/shrimp-body.ts", "w") as f:
    f.write("// Generated by scripts/shrimp-build.py from \"Shrimp Vector Design.jpg\" (2413x1614 px space).\n"
            "// Head with its legs, then seven nested abdomen segments (each carries the ones behind it,\n"
            "// plus its swimmerets and, on the last, the tail fan). Whiskers are in shrimp-whiskers.ts.\n"
            f"export const SHRIMP_BODY = {json.dumps(markup)};\n")
print("pivots", pivots)
print("pieces", [b for b in boxes])
