"""Build the boxing mantis shrimp mark from a dark-on-light image.

Usage: python3 scripts/mantis-build.py <source.png> [--preview out.png]
(run from the repo root; needs Pillow and potrace)

The source (an 892x392 screenshot of a mantis shrimp on grey wood) is upscaled 3x and
thresholded. The folded club and the other moving parts (antennae, walking legs, the paddles
under the tail, the tail fan) are cut out by hand-drawn polygons, each with a pivot where it
meets the body, and traced separately with potrace. Writes src/components/mantis-body.ts;
coordinates are the 3x image's pixels (2676x1176).
"""
import json, os, re, subprocess, sys, tempfile
from PIL import Image, ImageDraw, ImageFilter

src = sys.argv[1]
preview = sys.argv[sys.argv.index("--preview") + 1] if "--preview" in sys.argv else None

# name: (polygon, pivot). The club is "claw"; the rest animate in CSS by name.
PARTS = {
    "claw":     ([(1680, 622), (1870, 602), (2040, 640), (2052, 720), (1962, 812), (1730, 822), (1680, 762)], (2030, 645)),
    "antennae": ([(2062, 290), (2600, 290), (2600, 880), (2062, 880)], (2050, 430)),
    "leg-1":    ([(1060, 800), (1250, 800), (1250, 990), (1060, 990)], (1160, 800)),
    "leg-2":    ([(1250, 800), (1460, 800), (1460, 990), (1250, 990)], (1350, 800)),
    "leg-3":    ([(1460, 790), (1830, 790), (1830, 960), (1460, 960)], (1560, 790)),
    "pleo-1":   ([(680, 695), (790, 695), (790, 1000), (680, 1000)], (735, 695)),
    "pleo-2":   ([(790, 695), (900, 695), (900, 1000), (790, 1000)], (845, 695)),
    "pleo-3":   ([(900, 695), (1010, 695), (1010, 1000), (900, 1000)], (955, 695)),
    "pleo-4":   ([(1010, 695), (1060, 695), (1060, 1000), (1010, 1000)], (1035, 695)),
    "tail":     ([(300, 380), (640, 380), (640, 1080), (300, 1080)], (650, 600)),
}

im = Image.open(src).convert("L")
big = im.resize((im.width * 3, im.height * 3), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1.2))
bw = big.point(lambda v: 0 if v < 60 else 255, "L")
W, H = bw.size
pb = bw.load()
body = bw.copy(); po = body.load()
parts = {}
for name, (poly, pivot) in PARTS.items():
    mask = Image.new("L", (W, H), 0); ImageDraw.Draw(mask).polygon(poly, fill=255); pm = mask.load()
    img = Image.new("L", (W, H), 255); pi = img.load()
    xs, ys = [], []
    x0, x1 = max(0, min(p[0] for p in poly)), min(W - 1, max(p[0] for p in poly))
    y0, y1 = max(0, min(p[1] for p in poly)), min(H - 1, max(p[1] for p in poly))
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if pm[x, y] and po[x, y] == 0:
                pi[x, y] = 0; po[x, y] = 255; xs.append(x); ys.append(y)
    if not xs:
        continue
    half_x = max(abs(max(xs) - pivot[0]), abs(min(xs) - pivot[0])) + 6
    half_y = max(abs(max(ys) - pivot[1]), abs(min(ys) - pivot[1])) + 6
    parts[name] = (img, [pivot[0] - half_x, pivot[1] - half_y, 2 * half_x, 2 * half_y])

if preview:
    cols = [(220,40,40),(40,140,220),(40,170,80),(200,120,20),(150,60,200),(0,160,160),(230,90,160),(120,120,0),(90,90,90),(255,140,0)]
    vis = Image.new("RGB", (W, H), (250, 250, 250)); pv = vis.load()
    for y in range(H):
        for x in range(W):
            if po[x, y] == 0: pv[x, y] = (23, 23, 23)
    for i, (name, (img, _)) in enumerate(parts.items()):
        pi = img.load()
        for y in range(H):
            for x in range(W):
                if pi[x, y] == 0: pv[x, y] = cols[i % len(cols)]
    vis.crop((280, 120, 2620, 1110)).resize((1170, 495)).save(preview)
    sys.exit()

work = tempfile.mkdtemp()
def trace(img, name):
    bmp, svg = os.path.join(work, name + ".bmp"), os.path.join(work, name + ".svg")
    img.convert("1").save(bmp)
    subprocess.run(["potrace", bmp, "-s", "-o", svg, "--turdsize", "20", "--alphamax", "1.0", "--opttolerance", "0.4"], check=True)
    paths = " ".join(re.sub(r"\s+", " ", p) for p in re.findall(r'<path d="[^"]*"/>', open(svg).read(), re.S))
    return f'<g transform="translate(0,{H}) scale(0.1,-0.1)">{paths}</g>'

items = [f'  {{ name: "{n}", pad: {pad}, svg: {json.dumps(trace(img, n))} }}' for n, (img, pad) in parts.items()]
with open("src/components/mantis-body.ts", "w") as f:
    f.write("// Generated by scripts/mantis-build.py (2676x1176 px space). Moving parts are cut out so they can animate;\n"
            "// `pad` is an invisible box centred on where each part meets the body, so CSS rotates it about that point.\n"
            f"export const MANTIS_BODY = {json.dumps(trace(body, 'body'))};\n"
            "export const MANTIS_PARTS = [\n" + ",\n".join(items) + ",\n] as const;\n")
print("wrote src/components/mantis-body.ts with", list(parts))
