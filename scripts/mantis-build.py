"""Build the boxing mantis shrimp mark from a dark-on-light image.

Usage: python3 scripts/mantis-build.py <source.png>   (run from the repo root; needs Pillow and potrace)

The source (an 892x392 screenshot of a mantis shrimp on grey wood) is upscaled 3x and thresholded,
the folded club is cut off at its joint so it can strike, and body and club are traced with potrace.
Writes src/components/mantis-body.ts; coordinates are the 3x image's pixels (2676x1176).
"""
import json, os, re, subprocess, sys, tempfile
from PIL import Image, ImageDraw, ImageFilter

src = sys.argv[1]
CLAW = [(1680, 622), (1870, 602), (2040, 640), (2052, 720), (1962, 812), (1730, 822), (1680, 762)]
PIVOT, HALF = (2030, 645), 420   # club joint; HALF sizes the invisible box CSS rotates about

im = Image.open(src).convert("L")
big = im.resize((im.width * 3, im.height * 3), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1.2))
bw = big.point(lambda v: 0 if v < 60 else 255, "L")
W, H = bw.size
mask = Image.new("L", (W, H), 0); ImageDraw.Draw(mask).polygon(CLAW, fill=255)
pb, pm = bw.load(), mask.load()
body = bw.copy(); claw = Image.new("L", (W, H), 255); po, pc = body.load(), claw.load()
for y in range(H):
    for x in range(W):
        if pb[x, y] == 0 and pm[x, y]:
            pc[x, y] = 0; po[x, y] = 255

work = tempfile.mkdtemp()
def trace(img, name):
    bmp, svg = os.path.join(work, name + ".bmp"), os.path.join(work, name + ".svg")
    img.convert("1").save(bmp)
    subprocess.run(["potrace", bmp, "-s", "-o", svg, "--turdsize", "20", "--alphamax", "1.0", "--opttolerance", "0.4"], check=True)
    paths = " ".join(re.sub(r"\s+", " ", p) for p in re.findall(r'<path d="[^"]*"/>', open(svg).read(), re.S))
    return f'<g transform="translate(0,{H}) scale(0.1,-0.1)">{paths}</g>'

with open("src/components/mantis-body.ts", "w") as f:
    f.write("// Generated by scripts/mantis-build.py (2676x1176 px space). The club is cut off at its joint so it can strike.\n"
            f"export const MANTIS_BODY = {json.dumps(trace(body, 'body'))};\n"
            f"export const MANTIS_CLAW = {json.dumps(trace(claw, 'claw'))};\n"
            f"export const MANTIS_CLAW_PAD = [{PIVOT[0] - HALF}, {PIVOT[1] - HALF}, {2 * HALF}, {2 * HALF}] as const;\n")
print("wrote src/components/mantis-body.ts")
